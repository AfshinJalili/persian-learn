function splitGraphemes(value: string): string[] {
  if (typeof Intl !== 'undefined' && 'Segmenter' in Intl) {
    return [...new Intl.Segmenter('fa', { granularity: 'grapheme' }).segment(value)].map(
      (part) => part.segment
    );
  }
  return Array.from(value);
}

export function splitObjectTokens(token: string): string[] {
  return splitGraphemes(token).filter((part) => part.trim().length > 0);
}

export function objectClusterColumns(count: number): number {
  if (count <= 1) return 1;
  if (count === 2) return 2;
  if (count === 3) return 3;
  if (count === 4) return 2;
  if (count <= 9) return 3;
  return 5;
}

export function objectClusterItemSize(count: number): number {
  if (count <= 1) return 64;
  if (count === 2) return 48;
  if (count === 3) return 40;
  if (count === 4) return 48;
  if (count <= 6) return 36;
  if (count <= 9) return 32;
  return 28;
}

export function resolveAvatarId(value: string): AvatarId {
  const match = AVATARS.find((item) => item.id === value || item.emoji === value);
  return match?.id ?? 'tulip';
}

export function AvatarArt({
  id,
  size = 54,
}: {
  id: string;
  size?: number;
}) {
  const avatar = AVATARS.find((item) => item.id === id || item.emoji === id) ?? AVATARS[0];
  const Art = avatar.Art;
  return (
    <span
      className="illus"
      style={{ width: size, height: size }}
    >
      <Art />
    </span>
  );
}

function SingleObjectArt({
  token,
  size,
  fluid = false,
}: {
  token: string;
  size: number;
  fluid?: boolean;
}) {
  const art = EMOJI_ART[token];
  return (
    <span
      className="illus"
      style={fluid ? undefined : { width: size, height: size }}
    >
      {art ?? (
        <span className="glyph" style={fluid ? undefined : { fontSize: Math.min(size, 72) }}>
          {token}
        </span>
      )}
    </span>
  );
}

export function ObjectCluster({
  token,
  tokens,
}: {
  token?: string;
  tokens?: string[];
}) {
  const parts = tokens ?? (token ? splitObjectTokens(token) : []);
  const count = parts.length;
  const cols = objectClusterColumns(count);
  const size = objectClusterItemSize(count);

  return (
    <span
      className="object-cluster"
      data-count={count}
      style={
        {
          '--object-cols': cols,
          '--object-size': `${size}px`,
        } as CSSProperties
      }
    >
      {parts.map((part, index) => (
        <SingleObjectArt key={`${part}-${index}`} token={part} size={size} fluid />
      ))}
    </span>
  );
}

export function ObjectArt({
  token,
  size = 96,
}: {
  token: string;
  size?: number;
}) {
  const parts = splitObjectTokens(token);
  if (parts.length > 1) {
    return <ObjectCluster token={token} />;
  }

  return <SingleObjectArt token={parts[0] ?? token} size={size} />;
}

export function looksLikeObjects(token: string): boolean {
  return splitGraphemes(token).some((part) => Boolean(EMOJI_ART[part]));
}
