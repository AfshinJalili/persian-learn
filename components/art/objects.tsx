export function normalizeObjectToken(token: string): string {
  return token
    .replace(/\uFE0F/g, '')
    .replace(/\uFE0E/g, '')
    .replace(/\u200D/g, '')
    .replace(/\u20E3/g, '')
    .replace(/[\u{1F3FB}-\u{1F3FF}]/gu, '');
}

