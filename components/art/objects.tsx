export function ObjectCluster({
  token,
  tokens,
  itemSize,
  layout = 'grid',
  boxWidth,
  boxHeight,
  cardWidth,
}: {
  token?: string;
  tokens?: string[];
  itemSize?: number;
  layout?: ObjectClusterLayout;
  boxWidth?: number;
  boxHeight?: number;
  cardWidth?: number;
}) {
  const parts = tokens ?? (token ? splitObjectTokens(token) : []);
  const count = parts.length;
  const gap = layout === 'match' || layout === 'row' ? OBJECT_MATCH_GAP : OBJECT_CLUSTER_GAP;
  const fitted = objectClusterLayoutForBox(
    count,
    boxWidth && boxWidth > 8 ? boxWidth : OBJECT_CARD_INNER_FALLBACK.width,
    boxHeight && boxHeight > 8 ? boxHeight : OBJECT_CARD_INNER_FALLBACK.height,
    gap,
    layout,
    cardWidth
  );
  const cols = fitted.cols;
  const rows = fitted.rows;
  const size = itemSize ?? fitted.size;

  return (
    <span
      className="object-cluster"
      data-count={count}
      data-cols={cols}
      data-rows={rows}
      data-layout={layout}
      style={
        {
          '--object-cols': cols,
          '--object-rows': rows,
          '--cluster-gap': `${gap}px`,
          '--dot': `${size}px`,
          '--object-size': `${size}px`,
        } as CSSProperties
      }
    >
      {parts.map((part, index) => (
        <SingleObjectArt key={`${part}-${index}`} token={part} size={size} />
      ))}
    </span>
  );
}

export function ObjectArt({
  token,
  size = 96,
}: {
  token: string;
  size?: number;
}) {
  const parts = splitObjectTokens(token);
  if (parts.length > 1) {
    return <ObjectCluster token={token} itemSize={size} />;
  }

  return <SingleObjectArt token={parts[0] ?? token} size={size} />;
}

export function looksLikeObjects(token: string): boolean {
  return splitGraphemes(token).some((part) => {
    const key = normalizeObjectToken(part);
    return Boolean(objectArtForToken(part) || DICE_PIP_COUNTS[part] || DICE_PIP_COUNTS[key]);
  });
}
