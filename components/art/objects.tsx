export type ObjectClusterLayout = 'grid' | 'row' | 'match' | 'picture';

function clusterWidth(cols: number, size: number, gap: number): number {
  return cols * size + gap * Math.max(0, cols - 1);
}

export function objectClusterLayoutForBox(
  count: number,
  innerWidth: number,
  innerHeight: number,
  gap: number = OBJECT_CLUSTER_GAP,
  layout: ObjectClusterLayout = 'grid',
  cardOffsetWidth?: number
): { cols: number; rows: number; size: number; unclamped: number } {
  if (count <= 0) {
    return { cols: 1, rows: 1, size: 0, unclamped: 0 };
  }

  if (count === 1) {
    const widthBasis =
      cardOffsetWidth && cardOffsetWidth > 8 ? cardOffsetWidth : innerWidth;
    const unclamped =
      layout === 'picture'
        ? innerWidth
        : layout === 'row' || layout === 'match'
          ? Math.min(
              widthBasis * OBJECT_SINGLE_WIDTH_RATIO,
              innerWidth,
              innerHeight,
              OBJECT_MATCH_SINGLE_MAX
            )
          : Math.max(
              Math.min(widthBasis * OBJECT_SINGLE_WIDTH_RATIO, innerWidth, innerHeight),
              // Never smaller than each item of a 2-item card in the same box
              // (narrow three-across cards stack two items at nearly full width).
              objectClusterLayoutForBox(2, innerWidth, innerHeight, gap, layout).unclamped
            );
    return {
      cols: 1,
      rows: 1,
      unclamped,
      size: Math.max(OBJECT_CLUSTER_MIN_SIZE, Math.floor(unclamped)),
    };
  }

  const sizeFor = (cols: number, rows: number) => {
    const sizeW = (innerWidth - gap * Math.max(0, cols - 1)) / cols;
    const sizeH = (innerHeight - gap * Math.max(0, rows - 1)) / rows;
    return Math.min(sizeW, sizeH);
  };

  if (count === 3 && (layout === 'grid' || layout === 'picture')) {
    const candidates = [
      { cols: 2, rows: 2, unclamped: sizeFor(2, 2) },
      { cols: 1, rows: 3, unclamped: sizeFor(1, 3) },
      { cols: 3, rows: 1, unclamped: sizeFor(3, 1) },
    ];
    const best = candidates.reduce((current, next) =>
      next.unclamped > current.unclamped + 0.25 ? next : current
    );
    return {
      ...best,
      size: Math.max(OBJECT_CLUSTER_MIN_SIZE, Math.floor(best.unclamped)),
    };
  }

  if (layout === 'row') {
    const score = (cols: number, rows: number) => {
      const sizeW = (innerWidth - gap * Math.max(0, cols - 1)) / cols;
      const sizeH = (innerHeight - gap * Math.max(0, rows - 1)) / rows;
      return Math.min(
        sizeW,
        Number.isFinite(sizeH) && sizeH > 8 ? sizeH : sizeW
      );
    };
    const fill = (cols: number, size: number) =>
      (cols * size + gap * Math.max(0, cols - 1)) / Math.max(1, innerWidth);
    const wrapped = {
      cols: Math.min(5, count),
      rows: count > 5 ? 2 : 1,
      unclamped: score(Math.min(5, count), count > 5 ? 2 : 1),
    };
    const oneRow = { cols: count, rows: 1, unclamped: score(count, 1) };
    const wrappedOk = fill(wrapped.cols, wrapped.unclamped) >= 0.6;
    const oneRowOk = fill(oneRow.cols, oneRow.unclamped) >= 0.6;
    const best =
      wrappedOk === oneRowOk
        ? oneRow.unclamped > wrapped.unclamped + 0.25
          ? oneRow
          : wrapped
        : oneRowOk
          ? oneRow
          : wrapped;
    return {
      ...best,
      size: Math.max(8, Math.floor(best.unclamped)),
    };
  }

  const maxCols = Math.min(5, count);
  let best = { cols: 1, rows: count, unclamped: sizeFor(1, count) };
  for (let cols = 2; cols <= maxCols; cols += 1) {
    const rows = Math.ceil(count / cols);
    if (layout === 'match' && rows > 2) {
      continue;
    }
    const unclamped = sizeFor(cols, rows);
    const bigger = unclamped > best.unclamped + 0.25;
    const same = Math.abs(unclamped - best.unclamped) <= 0.25;
    const wider =
      clusterWidth(cols, unclamped, gap) > clusterWidth(best.cols, best.unclamped, gap);
    if (bigger || (same && wider)) {
      best = { cols, rows, unclamped };
    }
  }

  if (layout === 'grid' || layout === 'match' || layout === 'picture') {
    return {
      ...best,
      size: Math.max(8, Math.floor(best.unclamped)),
    };
  }

  const _exhaustive: never = layout;
  return _exhaustive;
}

export function objectClusterColumns(
  count: number,
  layout: ObjectClusterLayout = 'grid',
  innerWidth = OBJECT_CARD_INNER_FALLBACK.width,
  innerHeight = OBJECT_CARD_INNER_FALLBACK.height
): number {
  return objectClusterLayoutForBox(count, innerWidth, innerHeight, OBJECT_CLUSTER_GAP, layout).cols;
}

export function objectClusterRows(
  count: number,
  layout: ObjectClusterLayout = 'grid',
  innerWidth = OBJECT_CARD_INNER_FALLBACK.width,
  innerHeight = OBJECT_CARD_INNER_FALLBACK.height
): number {
  return objectClusterLayoutForBox(count, innerWidth, innerHeight, OBJECT_CLUSTER_GAP, layout).rows;
}

export function objectClusterNeedsWideCard(count: number): boolean {
  return (
    objectClusterLayoutForBox(
      count,
      OBJECT_CARD_INNER_FALLBACK.width,
      OBJECT_CARD_INNER_FALLBACK.height
    ).unclamped < OBJECT_CLUSTER_MIN_SIZE
  );
}

