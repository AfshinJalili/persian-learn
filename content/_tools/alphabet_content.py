# Reading track, 12 units following research §4.1 (A0–A11) and the §2.1 sign order.
# Every intro that introduces a sign lists it in payload.teaches; validate.py enforces the order and
# that every on-screen Persian string uses only signs taught so far (§2.4 rule).
NONCONN_SRC = set("اآدذرزژو")
SK = "\u0652"   # sukun: shown in ey/ow names (زِیْنَب، گُوْهَر) so و/ی read as consonants
MARKCH = {"@": "زبر", "#": "زیر", "$": "پیش", "*": "تشدید", SK: "ساکن"}
NAME = {"ا": "الف", "آ": "آ", "ب": "ب#", "پ": "پ#", "ت": "ت#", "ث": "ث#", "ج": "جیم", "چ": "چ#",
        "ح": "ح#", "خ": "خ#", "د": "دال", "ذ": "ذال", "ر": "ر#", "ز": "ز#", "ژ": "ژ#", "س": "سین",
        "ش": "شین", "ص": "صاد", "ض": "ضاد", "ط": "طا", "ظ": "ظا", "ع": "عین", "غ": "غین", "ف": "ف#",
        "ق": "قاف", "ک": "کاف", "گ": "گاف", "ل": "لام", "م": "میم", "ن": "نون", "و": "واو",
        "ه": "ه#", "ی": "ی#"}
FORMS = {"آ": ["آ", "_آ", "_آ", "آ"]}
for _l in "ادذرزژو": FORMS[_l] = [_l, "_" + _l, "_" + _l, _l]
for _l in "بپتثجچحخسشصضطظعغفقکگلمنهی": FORMS[_l] = [_l + "_", "_" + _l + "_", "_" + _l, _l]

def split_word(w):
    out = []
    for ch in w:
        if ch in MARKCH and out: out[-1] += ch
        else: out.append(ch)
    return out

def spell(w):
    parts = []
    for g in split_word(w):
        if g == " ": continue
        n = NAME[g[0]]
        if len(g) > 1: n += " با " + " و ".join(MARKCH[c] for c in g[1:])
        parts.append(n)
    return "، ".join(parts)

def segs(w):
    pieces, cur = [], ""
    for g in split_word(w):
        cur += g
        if g[0] in NONCONN_SRC: pieces.append(cur); cur = ""
    if cur: pieces.append(cur)
    return pieces

# ---------------- helpers ----------------
def TEACH(t, display, audio, sg, visual=""):
    t.intro(display, audio, visual, teaches=sg)

def INFO(t, display, audio, visual=""):
    t.intro(display, audio, visual)

def TR(t, l, tip=""):
    t.trace(l, f"حالا با انگشت، «{NAME[l]}» را روی خط~ها بکشید. {tip}".strip(), FORMS[l])

def FIND(t, ans, distr, audio=None, fw=None):
    t.listen(audio or f"«{NAME[ans[0]] if ans[0] in NAME and len(ans) == 1 else ans}» را پیدا کنید.", ans, distr, "letter", fw=fw)

def WI(t, w, emoji, tail=""):
    t.intro(w, f"{spell(w)}: «{w}». {tail}".strip(), emoji)

BUILD_AUDIO = ["با این حرف~ها «{w}» را بسازید.", "حالا «{w}» را بسازید؛ از راست شروع کنید.",
               "حرف~ها را به ترتیب بچینید تا «{w}» ساخته شود."]
def WB(t, w, emoji, extra):
    t.build(emoji, split_word(w), extra, t._rot("build_audio", BUILD_AUDIO).format(w=w))

def W2(t, w, emoji, tail, extra):
    WI(t, w, emoji, tail); WB(t, w, emoji, extra)

def TAP(t, w, emoji, distr, audio="این را بخوانید. کدام تصویر است؟"):
    t.tap(w, audio, emoji, distr)

def LW(t, ans, distr, audio=None):
    t.listen(audio or f"«{ans}» را پیدا کنید.", ans, distr, "word")

def M(t, pairs, audio="هر کلمه را به تصویرش وصل کنید."):
    t.match(pairs, audio)

def BP(t, w, audio=None):
    ans = "|".join(segs(w))
    g = split_word(w)
    cands = [w, "|".join(g)]
    p = segs(w)
    if len(p) > 1: cands.append("|".join([p[0] + p[1]] + p[2:]))
    out = []
    for c in cands:
        if c != ans and c not in out: out.append(c)
    t.ex("break_points", "✂️", audio or f"«{w}» کجا از هم جدا می~شود؟ بعد از حرف~هایی که به بعدی نمی~چسبند، کلمه باز می~شود.",
         {"word": w}, ans, out[:2])

# ---- A0 (no letters on screen) ----
def TAPP(t, audio, ans, distr):
    t.tap("🔊", audio, ans, distr)
def CLAP(t, audio, n):
    t.listen(audio, "👏" * n, ["👏" * x for x in (1, 2, 3, 4) if x != n][:2] if n < 3 else ["👏" * (n - 1), "👏" * (n + 1)], "claps", prompt="👏")
def SAME(t, a, b, same):
    t.listen(f"گوش کنید: «{a}» و «{b}». صدای اولشان یکی است؟", "✅" if same else "❌", ["❌" if same else "✅"], "same", prompt="👂")


