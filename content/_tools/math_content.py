def fmt_money(v):
    k, r = divmod(v, 1000)
    if v >= 1000 and r == 0: return "هزار تومان" if k == 1 else f"{D(k)} هزار تومان"
    return f"{D(v)} تومان"
def money_near(v):
    c = [x for x in (v - 10000, v + 10000, v + 20000, v - 20000) if x > 0 and x != v]
    return [fmt_money(x) for x in c[:2]]
def count_money(t, items, audio):
    t.ex("count_money", "؟", audio, {"items": items}, fmt_money(sum(items)), money_near(sum(items)))
def listen_money(t, audio, v, distr=None):
    t.listen(audio, fmt_money(v), distr or money_near(v), "money")
def pay(t, item, price, wallet, audio):
    t.ex("pay_amount", "💵", audio, {"item": item, "price": price, "wallet": wallet}, fmt_money(price), money_near(price))
def change(t, item, price, paid, audio):
    t.ex("make_change", "💵", audio, {"item": item, "price": price, "paid": paid},
         fmt_money(paid - price), money_near(paid - price))
