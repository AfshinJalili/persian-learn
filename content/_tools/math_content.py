def cphrase(h, m):
    nxt = h % 12 + 1
    return {0: f"ساعت {D(h)}", 30: f"ساعت {D(h)} و نیم", 15: f"ساعت {D(h)} و ربع",
            45: f"یک ربع به {D(nxt)}"}[m]
def clock_near(h, m):
    prev, nxt = (h - 2) % 12 + 1, h % 12 + 1
    if m == 0:
        mir = 12 - h if 12 - h not in (0, h) else (h + 5) % 12 + 1
        n2 = nxt if nxt != mir else prev
        return [cphrase(mir, 0), cphrase(n2, 0)]
    if m == 30: return [cphrase(h, 0), cphrase(prev, 30)]
    if m == 15: return [cphrase(h, 45), cphrase(h, 30)]
    return [cphrase(h, 15), cphrase(nxt, 15)]
def clock(t, h, m, style, audio, fw=None):
    t.ex("read_clock", "🕒", audio, {"hour": h, "minute": m, "style": style}, cphrase(h, m), clock_near(h, m), fw=fw)
CLOCK_EMOJI = {(h, 0): e for h, e in zip(range(1, 13), "🕐🕑🕒🕓🕔🕕🕖🕗🕘🕙🕚🕛")}
CLOCK_EMOJI.update({(h, 30): e for h, e in zip(range(1, 13), "🕜🕝🕞🕟🕠🕡🕢🕣🕤🕥🕦🕧")})
def tap_clock(t, h, m, audio, d1, d2):
    t.tap(cphrase(h, m), audio, CLOCK_EMOJI[(h, m)], [CLOCK_EMOJI[d1], CLOCK_EMOJI[d2]], prompt="🕒")
