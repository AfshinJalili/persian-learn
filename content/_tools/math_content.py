def count(t, objkey, n, pool=ALL, audio=None):
    e, name = OBJ[objkey]
    t.ex("count_objects", "؟", audio or t._rot("count_audio", COUNT_AUDIO).format(n=name),
         {"objects": e, "count": n}, D(n), [D(x) for x in near(n, pool)])

def ten_frame(t, n, audio, objects="🔴", pool=ALL):
    t.ex("ten_frame", "؟", audio, {"count": n, "objects": objects}, D(n), [D(x) for x in near(n, pool)])

def listen_digit(t, n, pool=ALL):
    a = t._rot("ld", ["عدد «{w}» را پیدا کنید و لمس کنید.", "کدام عدد «{w}» است؟", "«{w}» را نشان بدهید."])
    t.listen(a.format(w=W[n]), D(n), [D(x) for x in near(n, pool)], "digit")

def listen_num(t, audio, n, pool=ALL):
    t.listen(audio, D(n), [D(x) for x in near(n, pool)], "digit")

def tap_digit(t, n, objkey, pool=ALL):
    e, name = OBJ[objkey]
    t.tap(D(n), f"این عدد را ببینید. کدام تصویر به همین تعداد {name} دارد؟", rep(e, n),
          [rep(e, x) for x in near(n, pool)])

def tap_spoken(t, n, objkey, nums, audio=None):
    e, name = OBJ[objkey]
    others = [x for x in nums if x != n][:2]
    t.tap("🔊", audio or f"{W[n]} {name} را نشان بدهید.", rep(e, n), [rep(e, x) for x in others])

def shape_digit(t, n):
    t.choose_digit(D(n), f"به این عدد خوب نگاه کنید؛ این «{W[n]}» است. همین شکل را در میان گزینه~ها پیدا کنید.",
                   D(n), [D(x) for x in SIM[n]], prompt="👀")

def intro_digit(t, n):
    e, _ = OBJ[INTRO_OBJ[n]]
    t.intro(D(n), DESC[n], rep(e, n))

def match_digits(t, nums, objkey):
    e, name = OBJ[objkey]
    t.match([(D(x), rep(e, x)) for x in sorted(nums)], f"هر عدد را به تصویری وصل کنید که همان تعداد {name} دارد.")

def digit_pair_lesson(t, a, b, known, objs):
    o1, o2, o3, o4 = objs
    intro_digit(t, a); count(t, o1, a, known); tap_digit(t, a, o2, known)
    intro_digit(t, b); count(t, o3, b, known); listen_digit(t, b, known); shape_digit(t, b)
    listen_digit(t, a, known)
    others = [x for x in sorted(known) if x not in (a, b)][-2:]
    match_digits(t, others + [a, b], o4)
    count(t, o4, b, known)

def line_audio(s, m):
    if m > 0: return f"روی خط عدد از «{W[s]}» شروع کنید و {W[m]} قدم جلو بروید. به کدام عدد می~رسید؟"
    return f"روی خط عدد از «{W[s]}» شروع کنید و {W[-m]} قدم به عقب برگردید. به کدام عدد می~رسید؟"

def eq(t, a, op, b, objkey=None, audio=None):
    res = a + b if op == "+" else a - b
    e, name = OBJ[objkey] if objkey else ("", "")
    if audio is None:
        if objkey and op == "+": audio = f"{W[a]} {name} و {W[b]} {name}؛ روی هم چند {name} می~شود؟"
        elif objkey: audio = f"{W[a]} {name} داشتید و {W[b]} تا را برداشتید. چند {name} ماند؟"
        elif op == "+": audio = f"«{W[a]}» به~اضافه^ «{W[b]}» چند می~شود؟"
        else: audio = f"«{W[a]}» منهای «{W[b]}» چند می~شود؟"
    t.ex("equation", f"{D(a)} {op} {D(b)} = ؟", audio, {"a": a, "op": op, "b": b, "objects": e},
         D(res), [D(x) for x in near(res, ALL)])

def frame_str(filled, total=10, a="🔴", b="⚪"): return a * filled + b * (total - filled)

